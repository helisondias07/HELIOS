"use strict";

const { contextBridge, ipcRenderer } = require("electron");

contextBridge.exposeInMainWorld("api", {
  getSettings: () => ipcRenderer.invoke("settings:get"),
  setSettings: (patch) => ipcRenderer.invoke("settings:set", patch),
  testKeys: () => ipcRenderer.invoke("settings:test"),
  transcribe: (buf, mime, who, mode) => ipcRenderer.invoke("audio:transcribe", buf, mime, who, mode),
  sayEn: (text, rid) => ipcRenderer.invoke("ai:sayEn", text, rid),
  warm: () => ipcRenderer.invoke("net:warm"),
  research: (lines, query, rid) => ipcRenderer.invoke("ai:research", lines, query, rid),
  openLink: (url) => ipcRenderer.invoke("link:open", url),
  screenPreview: () => ipcRenderer.invoke("screen:preview"),
  screenCancel: () => ipcRenderer.invoke("screen:cancel"),
  translateBatch: (items, history, rid) => ipcRenderer.invoke("ai:translateBatch", items, history, rid),
  glossaryGet: () => ipcRenderer.invoke("glossary:get"),
  glossarySet: (text) => ipcRenderer.invoke("glossary:set", text),
  glossaryOpen: () => ipcRenderer.invoke("glossary:open"),
  searchBuild: (term, lastLine) => ipcRenderer.invoke("search:build", term, lastLine),
  searchOpen: (query) => ipcRenderer.invoke("search:open", query),
  getRate: () => ipcRenderer.invoke("rate:get"),
  translate: (text) => ipcRenderer.invoke("ai:translate", text),
  suggest: (lines, lang, rid) => ipcRenderer.invoke("ai:suggest", lines, lang, rid),
  explain: (lines, term, rid) => ipcRenderer.invoke("ai:explain", lines, term, rid),
  summary: (lines, rid) => ipcRenderer.invoke("ai:summary", lines, rid),
  ask: (lines, question, withScreen, rid) => ipcRenderer.invoke("ai:ask", lines, question, withScreen, rid),
  roteiro: (lines, topic, rid) => ipcRenderer.invoke("ai:roteiro", lines, topic, rid),
  onDelta: (cb) => ipcRenderer.on("ai:delta", (_event, rid, text) => cb(rid, text)),
  saveHistory: (id, text) => ipcRenderer.invoke("history:save", id, text),
  openHistory: () => ipcRenderer.invoke("history:open"),
  setHeight: (height) => ipcRenderer.send("win:height", height),
  hide: () => ipcRenderer.send("win:hide"),
  onMeetingStop: (cb) => ipcRenderer.on("meeting:stop", (_event, info) => cb(info)),
  quit: () => ipcRenderer.send("win:quit"),
  focus: () => ipcRenderer.send("win:focus"),
  personalInfo: () => ipcRenderer.invoke("personal:info"),
  openPersonal: () => ipcRenderer.invoke("personal:open"),
  onPersonal: (cb) => ipcRenderer.on("personal", (_event, info) => cb(info)),
  onHotkey: (cb) => ipcRenderer.on("hotkey", (_event, name) => cb(name)),
  onHotkeysFailed: (cb) => ipcRenderer.on("hotkeys-failed", (_event, list) => cb(list)),
  liveStart: (description) => ipcRenderer.invoke("livecoding:start", description),
  liveNext: (id) => ipcRenderer.invoke("livecoding:next", id),
  onLiveSession: (cb) => ipcRenderer.on("livecoding:session", (_event, session) => cb(session)),
});
